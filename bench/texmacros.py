"""LaTeX macros for every timed number of the paper, from summary.csv (bench/reproduce.sh), so no such
number is typed by hand. Rounding is decimal ROUND_HALF_UP on the exact values of summary.csv: rates to
three significant digits, ratios to two decimals (binary floats would turn 4.55 into 4.5, ISS-0054).

usage: python3 texmacros.py summary.csv > paper/generated/numbers.tex
In LaTeX: \\rate{CELL}{TOOL} (median GCUPS), \\rateq{CELL}{TOOL} (its Q1--Q3), \\ratio{CELL}{A}{B} (median
of the per-repetition ratios A/B), \\ratioq{CELL}{A}{B} (their Q1--Q3). An unknown key is a LaTeX error.
"""
import csv
import sys
from decimal import ROUND_HALF_UP, Decimal


def sig3(x):
    d = Decimal(x)
    if d == 0:
        return "0"
    q = Decimal(1).scaleb(d.adjusted() - 2)
    r = d.quantize(q, rounding=ROUND_HALF_UP)
    return format(r, "f") if q < 1 else str(int(r))


def dec2(x):
    return format(Decimal(x).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP), "f")


def main():
    out = ["% Generated by bench/texmacros.py from " + sys.argv[1].replace("\\", "/").split("/bench/")[-1] + "; do not edit.",
           "\\makeatletter"]
    for name, prefix in (("rate", "r"), ("rateq", "rq"), ("ratio", "x"), ("ratioq", "xq")):
        args = "[3]" if name.startswith("ratio") else "[2]"
        key = "#1@#2@#3" if name.startswith("ratio") else "#1@#2"
        out.append(f"\\newcommand{{\\{name}}}{args}{{\\ifcsname bd@{prefix}@{key}\\endcsname\\csname bd@{prefix}@{key}\\endcsname"
                   f"\\else\\PackageError{{numbers}}{{no {name} {key.replace('@', ' ')}}}{{}}\\fi}}")
    for r in csv.DictReader(open(sys.argv[1])):
        if r["kind"] == "rate":
            k = f"{r['cell']}@{r['tool']}"
            out.append(f"\\expandafter\\def\\csname bd@r@{k}\\endcsname{{{sig3(r['median'])}}}")
            out.append(f"\\expandafter\\def\\csname bd@rq@{k}\\endcsname{{{sig3(r['q1'])}--{sig3(r['q3'])}}}")
        else:
            k = f"{r['cell']}@{r['tool']}@{r['versus']}"
            out.append(f"\\expandafter\\def\\csname bd@x@{k}\\endcsname{{{dec2(r['median'])}}}")
            out.append(f"\\expandafter\\def\\csname bd@xq@{k}\\endcsname{{{dec2(r['q1'])}--{dec2(r['q3'])}}}")
    out.append("\\makeatother")
    print("\n".join(out))


if __name__ == "__main__":
    main()
