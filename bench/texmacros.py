"""LaTeX macros for every timed number of the paper, from summary.csv (bench/reproduce.sh), so no such
number is typed by hand. Rounding is decimal ROUND_HALF_UP on the exact values of summary.csv: rates,
seconds and megabytes to three significant digits, ratios to two decimals (binary floats would turn 4.55
into 4.5, ISS-0054).

usage: python3 texmacros.py summary.csv [summary-bestperf.csv] > paper/generated/numbers.tex
In LaTeX: \\rate{CELL}{TOOL} (median GCUPS), \\rateq{CELL}{TOOL} (its Q1--Q3), \\ratio{CELL}{A}{B} (median
of the per-repetition ratios A/B), \\ratioq{CELL}{A}{B} (their Q1--Q3), \\hits{CELL} (scan hits),
\\csec{CELL}{SCHEME} and \\cmb{CELL}{SCHEME} (compile step: median seconds and MaxRSS in MB, CELL is
compile-OS-MODE), \\insnw{CELL}{TOOL} and \\insnc{CELL}{TOOL} (retired instructions per column word and per
DP cell, three significant digits). An unknown key is a LaTeX error. Session statistics over the rates of tools that return
correct costs: \\iqrmed and \\iqrmax (median and largest interquartile range in percent of the median),
\\rangemax (largest range in percent of the median); with the second file, over the cells it repeats:
\\perfmin and \\perfmax (smallest and largest ratio of a median rate there to the same median here) and
\\perfshift (largest change of a median paired ratio between two tools of the same register width, after
rounding both to two decimals). Bounds are
rounded outwards (largest values up, smallest down), so "at most" and "from ... to" stay true.
"""
import csv
import os
import statistics
import sys
from decimal import ROUND_CEILING, ROUND_FLOOR, ROUND_HALF_UP, Decimal


def sig3(x):
    d = Decimal(x)
    if d == 0:
        return "0"
    q = Decimal(1).scaleb(d.adjusted() - 2)
    r = d.quantize(q, rounding=ROUND_HALF_UP)
    return format(r, "f") if q < 1 else str(int(r))


def secs(x):
    """Zig reports a compile step in whole seconds above one second, so print those without decimals."""
    d = Decimal(x)
    return str(int(d.quantize(Decimal(1), rounding=ROUND_HALF_UP))) if d >= 1 else sig3(d)


def dec2(x):
    return format(Decimal(x).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP), "f")


# macro name, number of key parts, csname prefix
MACROS = [("rate", 2, "r"), ("rateq", 2, "rq"), ("ratio", 3, "x"), ("ratioq", 3, "xq"), ("hits", 1, "h"),
          ("csec", 2, "cs"), ("cmb", 2, "cm"), ("insnw", 2, "iw"), ("insnc", 2, "ic")]


def main():
    sys.stdout.reconfigure(newline="\n")  # LF on Windows too
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = ["% Generated by bench/texmacros.py from " + os.path.relpath(sys.argv[1], root).replace("\\", "/") + "; do not edit.",
           "\\makeatletter"]
    for name, n, prefix in MACROS:
        key = "@".join(f"#{i}" for i in range(1, n + 1))
        out.append(f"\\newcommand{{\\{name}}}[{n}]{{\\ifcsname bd@{prefix}@{key}\\endcsname\\csname bd@{prefix}@{key}\\endcsname"
                   f"\\else\\PackageError{{numbers}}{{no {name} {key.replace('@', ' ')}}}{{}}\\fi}}")

    def define(prefix, key, value):
        out.append(f"\\expandafter\\def\\csname bd@{prefix}@{key}\\endcsname{{{value}}}")

    for r in csv.DictReader(open(sys.argv[1])):
        k = f"{r['cell']}@{r['tool']}"
        if r["kind"] == "rate":
            define("r", k, sig3(r["median"]))
            define("rq", k, f"{sig3(r['q1'])}--{sig3(r['q3'])}")
        elif r["kind"] == "ratio":
            k += f"@{r['versus']}"
            define("x", k, dec2(r["median"]))
            define("xq", k, f"{dec2(r['q1'])}--{dec2(r['q3'])}")
        elif r["kind"] == "hits":
            define("h", r["cell"], r["median"])
        elif r["kind"] == "seconds":
            define("cs", k, secs(r["median"]))
        elif r["kind"] == "megabytes":
            define("cm", k, sig3(r["median"]))
        elif r["kind"] in ("insnword", "insncell"):
            define("iw" if r["kind"] == "insnword" else "ic", k, sig3(r["median"]))

    rows = list(csv.DictReader(open(sys.argv[1])))
    ok = [r for r in rows if r["kind"] == "rate" and r["wrong_costs"] != "1" and Decimal(r["n"]) > 1]
    iqr = [(Decimal(r["q3"]) - Decimal(r["q1"])) / Decimal(r["median"]) * 100 for r in ok]
    span = [(Decimal(r["max"]) - Decimal(r["min"])) / Decimal(r["median"]) * 100 for r in ok]
    tenth = Decimal("0.1")
    stats = {"iqrmed": statistics.median(iqr).quantize(tenth, rounding=ROUND_HALF_UP),
             "iqrmax": max(iqr).quantize(tenth, rounding=ROUND_CEILING),
             "rangemax": max(span).quantize(Decimal(1), rounding=ROUND_CEILING)}
    if len(sys.argv) > 2:
        other = list(csv.DictReader(open(sys.argv[2])))
        here = {(r["kind"], r["cell"], r["tool"], r["versus"]): Decimal(r["median"]) for r in rows}
        there = {(r["kind"], r["cell"], r["tool"], r["versus"]): Decimal(r["median"]) for r in other}
        speed = [there[k] / here[k] for k in there if k[0] == "rate"]
        cent = Decimal("0.01")
        width = lambda tool: tool.rsplit("-", 1)[-1]  # avx2 or avx512: the paper compares equal register widths
        shift = [abs(there[k].quantize(cent, rounding=ROUND_HALF_UP) - here[k].quantize(cent, rounding=ROUND_HALF_UP))
                 for k in there if k[0] == "ratio" and width(k[2]) == width(k[3])]
        stats |= {"perfmin": min(speed).quantize(cent, rounding=ROUND_FLOOR),
                  "perfmax": max(speed).quantize(cent, rounding=ROUND_CEILING), "perfshift": max(shift)}
    for name, value in stats.items():
        out.append(f"\\newcommand{{\\{name}}}{{{value}}}")
    out.append("\\makeatother")
    print("\n".join(out))


if __name__ == "__main__":
    main()
